#!/usr/bin/env bash
# Invariant `generator-edges-declared`: every row of `.claude/generator-edges.tsv` is
# checked against the script it names. Nothing verified these rows before this file existed --
# the completeness guard compares the map against ONE TRACED RUN and the audit hook does not
# cross `exec()` -- so a wrong row was invisible to every guard in principle, and the table's
# first version already missed one.
#
# point 1 -- "found in the script" (rule 1). A path
# cell P is found in script S when P occurs, as a FIXED STRING (never a regex -- every path
# contains `.`), in the surviving text of some line of S once that line is truncated at the
# first `#` that is at line start or preceded by a space or tab (the same approximation
# `gate-jq-only-envelope.sh` uses, so the repo keeps one definition of "comment"). A boundary
# applies so a row naming `docs/ROADMAP.md` does not stay green when the script only names
# `docs/ROADMAP.md.bak` or `olddocs/ROADMAP.md`:
#   before P: not one of  A-Z a-z 0-9 . _
#   after  P: not one of  A-Z a-z 0-9 . _ / -
# The boundary is ASYMMETRIC on purpose, measured against the real table: a symmetric rule is red
# on cells shaped `${VAR:-docs/ROADMAP.md}`, where the character before the path
# is `-`. point 1 proves a path is NAMED, not that it is used, and it does not check read/write
# direction.
#
# "Fixed string" is byte-literal, and three sub-languages had to be told so. P reaches awk through
# ENVIRON, not `-v` (which expands backslash escapes, so `a\tb` would be searched as a TAB); it
# reaches git through `--literal-pathspecs` (a bare pathspec treats `[A]AA.sh` as a glob that
# matches a DIFFERENT tracked file, `AAA.sh` -- measured by review, not assumed); and it reaches
# the header `case` quoted, where bash already treats it literally.
#
# point 2 -- a `writes` cell W (not `-`) also passes when W is a git-TRACKED regular file whose FIRST
# LINE contains `GENERATED by S` (S = the script cell exactly as written in the row) followed by
# a space or end of line. `reads` cells never use this rule -- a header describes who wrote a
# file, never who reads it. An untracked file must not vouch for a row. A trailing CR is removed
# from that first line before matching, as the table parse below already does for rows: a CRLF
# checkout (`core.autocrlf=true`) must not turn a file nobody touched red.
#
# Exemption lines -- the only escape, one per (script, path):
#   #exempt<TAB><script><TAB><path><TAB><reason>
# A cell no rule vouches for passes when an exemption names its row's script and its path. The
# line starts with `#`, so both table readers skip it and neither changes. Four red states:
#   malformed  a line starting `#exempt` that is not exactly those 4 tab-separated fields, or
#              whose reason is empty or only whitespace -- a typo must not silently become a
#              comment. A prose `# exempt ...` (space after `#`) is an ordinary comment.
#   orphan     no row names that script with that path in reads or writes.
#   stale      every cell it names passes by point 1 or the header rule without it.
#   duplicate  a second line for the same (script, path); only the first one is used.
# Bash 3.2 (`/bin/bash`, which the gate runs) has no associative arrays, so exemptions live in
# parallel indexed arrays searched linearly -- the table has a handful of rows.
#
# NO ENVIRONMENT OVERRIDES. Neither the table path nor the repo root can be moved by an
# environment variable ("an environment variable is not a capability" --
# `gate-jq-only-envelope.sh` header; two earlier checks both let something outside a check redirect what
# it scanned). The root is derived from this script's own location; a fixture that wants a
# different root copies this script somewhere else rather than pointing an existing copy at a
# second tree. (This used to cite `test-input-map-fresh.sh` as the precedent it copied. That file
# was deleted, so the citation is gone rather than left pointing at nothing -- the
# pattern is still the same one `gate-jq-only-envelope.sh` uses.) (The one variable this
# script sets, GEDP_PATH, is how it hands a value to its own awk; nothing reads it from outside.)
#
# point 6 -- THE CONTENT HALF. Everything above checks that the table's DECLARATIONS are
# honest. It never checks that a generated file's CONTENT is current, and point 2's header rule cannot:
# a `GENERATED by S` first line says who wrote a file, never whether what follows is what S would
# write today. The original motivation died with `scripts/select-tests.sh`; its mechanism is repointed
# here at two files that really do drift silently. THE TWO SUBJECTS ARE NOT THE SAME KIND OF FILE,
# and giving them the same check DISABLED one of them -- measured in review, not reasoned:
#   [G1] `.claude/roadmap-lead-baseline.tsv` -- a RATCHET. It deliberately holds OLD values, and
#        the rule its consumer enforces (`roadmap-lead-length.sh`'s pinned-row branch) is "a pinned row may stay
#        as long as it is; it may not get longer". The first version of this half demanded the
#        file be byte-identical to a fresh generation, which is the same sentence as "every pin
#        equals today's measurement", and that had two measured consequences: while it was green
#        `lcols > pl` could NEVER fire, and when a row really did grow this check printed
#        `regenerate it` -- which re-pins at the grown length and turns BOTH guards green. A
#        guard that disables another guard, reading as complementary in the docs. So [G1] is now
#        checked with the ratchet's own semantics: NO PIN MAY GROW.
#   [G2] `docs/BACKLOG.md`'s index block -- rewritten wholesale by `scripts/backlog-toc.sh`, with
#        no freshness check of any kind before this phase. The failure shape: an entry
#        sits `open` in the committed index while `.claude/backlog-closures.tsv` says
#        `closed (completed)`. [G2] KEEPS
#        regenerate-and-compare, and that contract is right FOR IT: it is a pure DERIVED
#        artifact, so "what the generator produces today" is exactly what it should be, and
#        re-deriving catches drift shapes nobody predicted.
# Each subject declares its own comparison mode:
#   ratchet the artifact is a pinned baseline, one record per line, keyed on field 1. Its fourth
#           field reads `col=<n>`. Compare the WORKING TREE file against the same path at the
#           branch's merge-base and fail when any key present in BOTH has grown in column <n>. A
#           new key and a removed key are both allowed: an unpinned row must meet the bound
#           outright, which is already `roadmap-lead-length.sh`'s job and not this one's.
#   self    the generator has its own `--check` that writes nothing; ITS exit code is the verdict.
#           Its fourth field is the argument list to pass, and its FIFTH field is the exit code
#           that means "the artifact is stale" -- any OTHER non-zero code is could-not-run, and
#           the two must not collapse. `backlog-toc.sh` exits 1 for "differs" and 2..10 for
#           refused or could-not-run; calling all of them "is NOT current" asserted staleness
#           nothing measured AND recommended the operation that had just been declined.
#           The generator's stderr is captured, not discarded -- it is the only text that tells
#           the two cases apart.
#
# Every subject line has FIVE `|`-separated fields and the count is CHECKED. `${line#*|}` on a row
# with too few returns the whole remainder rather than failing, so a four-field row would have put
# the mode into the arg field and been reported as an unknown mode instead of a malformed line.
# A trailing CR is stripped before the fields are cut: under `core.autocrlf=true` this here-doc
# arrives with one, and it used to reach them (a known class).
#
# WHY THE MERGE-BASE AND NOT `HEAD:`. `git show HEAD:<artifact>` only catches an UNCOMMITTED edit
# -- once a grown pin is committed the check passes forever. Against the merge-base the claim is
# "this branch did not launder a pin", and an uncommitted edit is still caught, because the
# comparison reads the WORKING TREE file. A ratchet subject that exists while no merge-base can be
# resolved is COULD NOT RUN (exit 3), never a pass -- `longterm-candidates-not-in-diff.sh` makes
# the same call. An adopter is unaffected: an absent artifact is not applicable and never reaches
# the base lookup.
#
# ONLY COLUMN 3 (lead-cols) IS RATCHETED, and the missing half is missing on purpose. Column 2
# (name-cols) has no consumer: the pin is keyed on a digest of the name cell, so any change to the
# name yields a different key and the row stops being pinned. `roadmap-lead-length.sh`'s ONLY-THE-LEAD-IS-RATCHETED comment
# records that a name-cell ratchet was written first and its mutant SURVIVED, being unreachable by
# construction. That dead guard is not re-added here.
#
# THERE IS NO `stdout` MODE. One existed, byte-comparing a generator's stdout with the artifact,
# and [G1] was its only subject; when [G1] became a ratchet it had none left. Every other
# generator in this repo is python3, which the gate's envelope bans, so it could not be repointed
# either. It was deleted rather than left as machinery with no subject.
# point 5 -- the not-applicable hatch is OBSERVABLE. Every subject prints one line saying it was checked
# or skipped, and a summary says how many of how many. The hatch stays (an adopter repo has neither
# file), but "checked 2 of 2" and "0 of 2, 2 not applicable" no longer read the same.
#
# Verdicts: 0 pass or not applicable, 1 a violation (all of them printed, not only the first),
# 3 could not run (table unreadable, git unavailable, not a git work tree).
#
# Envelope: bash + awk + git + coreutils only. No python3, no jq IN THIS FILE -- stated precisely
# because the content half SHELLS OUT to two generators and one of them, gen-roadmap-lead-baseline.sh,
# uses jq. That is inside CLAUDE.md's rule (the gate's envelope bans python3, not jq) and it is
# written down rather than left for a reader to discover.
set -euo pipefail
cd "$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

NAME="generator-edges-declared"
TABLE=".claude/generator-edges.tsv"

# The table half being absent says nothing about the content half (point 5/point 6): an adopter with no
# edges table can still carry a generated artifact this repo declares, and a pass printed before
# anything looked would be exactly the vacuous pass this guard forbids.
not_applicable() {
  content_half
  if [ "${#content_fails[@]}" -gt 0 ]; then
    # The `ok` about the TABLE half goes FIRST on this path. It used to be the last line printed by
    # an rc=1 run, so the final thing a reader saw was an `ok` -- true about the half it names, and
    # the opposite of the verdict. The FAIL lines now close the output.
    printf 'ok  %s: table half not applicable -- no %s in this repo\n' "$NAME" "$TABLE"
    print_content_fails
    exit 1
  fi
  printf 'ok  %s: not applicable -- no %s in this repo\n' "$NAME" "$TABLE"
  exit 0
}

cannot_run() {
  printf 'COULD NOT RUN %s: %s\n' "$NAME" "$1" >&2
  exit 3
}

# --- point 6: the declared content subjects. Hand-written, one per line, FIVE `|`-separated fields:
#   <artifact>|<generator>|<mode>|<mode-arg, or - for none>|<stale-exit, or - when the mode has none>
# The last two are mode-specific, so every row carries one field that means nothing to it. That is a
# known wart: `ratchet` needs only the column and `self` only the argument list plus the stale code.
# A `mode` followed by `key=value` pairs would drop the field-count grammar and two of the four
# declaration-error branches; the count grammar exists because `${line#*|}` returns the whole
# remainder when a separator is missing, so a short row would otherwise be reported as an unknown
# mode -- a message pointing at the wrong field.
# Hand-written rather than discovered, for the reason `gate-jq-only-envelope.sh` gives about its own
# declared list: a glob would silently enrol files nobody meant to guard, and the alternative still
# ends in a hand-written list, so the staleness only moves. Adding a row here is a deliberate act.
# An artifact that is absent is NOT APPLICABLE (adopters have neither file). An artifact that is
# present while its generator is gone is a FAILURE, never a skip -- that is precisely the silent
# hole this half exists to close.
CONTENT_SUBJECTS="
.claude/roadmap-lead-baseline.tsv|scripts/gen-roadmap-lead-baseline.sh|ratchet|col=3|-
docs/BACKLOG.md|scripts/backlog-toc.sh|self|--check|1
"
# How many rows the block above has, written OUTSIDE the loop that reads it. See the summary at the
# end of `content_half` for why a loop cannot count itself honestly.
CONTENT_SUBJECTS_EXPECTED=2

content_fails=()
content_checked=0
content_skipped=0
content_total=0

# --- content_base_rev: resolve the revision a ratchet subject is compared against, once. Probes
# `origin/HEAD` then `origin/main` -- the same two-step `step-enforcement-table-current.sh` uses,
# so the repo keeps one answer to "what is the default branch". The result is cached INCLUDING the
# failure, so a repo without a base does not re-probe git once per subject. Returns non-zero when
# there is no base; the caller decides what that means, and for a ratchet subject it means COULD
# NOT RUN, never a pass.
CONTENT_BASE_REV=""
CONTENT_BASE_TRIED=0
content_base_rev() {
  if [ "$CONTENT_BASE_TRIED" -eq 0 ]; then
    CONTENT_BASE_TRIED=1
    CONTENT_BASE_REV="$(git merge-base origin/HEAD HEAD 2>/dev/null \
      || git merge-base origin/main HEAD 2>/dev/null || true)"
  fi
  [ -n "$CONTENT_BASE_REV" ]
}

# --- ratchet_report <base-file> <head-file> <now-file> <col>: one awk pass over THREE copies of a
# pinned baseline -- the value at the branch's merge-base, the value at HEAD, and the working tree.
# Emits, on stdout, one record per line:
#   G<TAB><key><TAB><bound><TAB><now-value><TAB><prefix><TAB><where the bound came from>
#                                                               a key that GREW -- a violation
#   M<TAB><side><TAB><line-no><TAB><text>                       a record this column cannot be
#                                                               read out of -- also a violation,
#                                                               because a baseline that cannot be
#                                                               parsed cannot be ratcheted, and a
#                                                               silent skip there is the vacuous
#                                                               pass this guard forbids
#   D<TAB><side><TAB><line-no><TAB><key>                        the same key twice on one side
#   C<TAB><n>                                                   how many keys were COMPARED
#
# THE BOUND IS THE MINIMUM OF THE TWO COMMITTED VALUES, and the second source was added because the
# first version's claim was measured false. It compared the working tree against the merge-base
# ONLY, and stated the claim as "this branch did not launder a pin". Reproduced: merge-base holds
# 100, the branch COMMITS a legitimate shrink to 60 -- which is the deliverable this whole mechanism
# exists to encourage -- and the working tree then grows it back to 80. Both guards green, because
# 80 is still under the merge-base's 100, and the wall grew on this branch with nothing objecting.
# The full laundering sequence was every step of the DOCUMENTED workflow: shorten a lead, re-pin,
# later let it grow, follow the printed `regenerate it`. So the bound now also reads HEAD: an
# uncommitted grow is caught against HEAD, and a grow committed earlier on the branch is caught
# because HEAD then holds the smaller value. `HEAD:` alone was rejected, correctly, for the
# opposite reason -- a grown pin committed before the check ran would pass forever -- and taking
# the MINIMUM keeps both directions instead of trading one for the other.
# Residual, stated rather than implied: a branch that commits a grow AND skips the gate on that
# commit is only caught if the grown value also exceeds the merge-base. The pre-push hook runs the
# task gate on every push, which is what makes the HEAD leg a chain rather than a single reading.
#
# The count is emitted because "no key grew" and "no key was looked at" are different answers and
# this repo has seen the collapse of that distinction. A key absent from BOTH committed
# copies (a new or renamed row) and a key absent from the working tree (a removed row) are both
# allowed, by the ratchet's own semantics -- the header says why.
# A DUPLICATE KEY takes the FIRST occurrence and is also reported. `roadmap-lead-length.sh`'s own
# reader ends its awk with `exit` after the first match, so first-wins is the consumer's answer and
# a second reader disagreeing with it is this repo's encoder-divergence class. Measured on the
# earlier last-wins version: a base holding the same key at 59 then 200 let a working-tree 80 pass
# green. The key is a cksum of the ROADMAP name cell, so duplicates need two rows with identical
# names, which makes this latent rather than live, and reported rather than assumed away.
# A trailing CR is stripped from every record, the same concession the table parse makes: a CRLF
# checkout must not turn a file nobody touched red.
# TABS INSIDE A REPORTED RECORD BECOME SPACES. The record is itself TSV and the shell reader splits
# on TAB, so passing it through unchanged handed the reader only its first field -- which, for a
# malformed row, is the one field that was fine.
ratchet_report() {
  GEDR_COL="$4" GEDR_BASE="$1" GEDR_HEAD="$2" awk '
    BEGIN {
      col = ENVIRON["GEDR_COL"] + 0; compared = 0
      basef = ENVIRON["GEDR_BASE"]; headf = ENVIRON["GEDR_HEAD"]
    }
    function clean(s) { sub(/\r$/, "", s); return s }
    function shown(s) { gsub(/\t/, " ", s); return s }
    # Returns the value, or "" when this line is not a usable record (having reported why).
    function record(side, line,   n) {
      n = split(line, f, "\t")
      if (n < col || f[col] !~ /^[0-9]+$/) {
        printf "M\t%s\t%d\t%s\n", side, FNR, shown(line)
        return ""
      }
      return f[col]
    }
    FILENAME == basef {
      line = clean($0)
      if (line == "" || substr(line, 1, 1) == "#") next
      v = record("the merge-base copy", line)
      if (v == "") next
      if (f[1] in base) { printf "D\tthe merge-base copy\t%d\t%s\n", FNR, f[1]; next }
      base[f[1]] = v
      next
    }
    FILENAME == headf {
      line = clean($0)
      if (line == "" || substr(line, 1, 1) == "#") next
      v = record("the HEAD copy", line)
      if (v == "") next
      if (f[1] in head) { printf "D\tthe HEAD copy\t%d\t%s\n", FNR, f[1]; next }
      head[f[1]] = v
      next
    }
    {
      line = clean($0)
      if (line == "" || substr(line, 1, 1) == "#") next
      v = record("the working tree copy", line)
      if (v == "") next
      k = f[1]
      if (k in now) { printf "D\tthe working tree copy\t%d\t%s\n", FNR, k; next }
      now[k] = v
      bound = ""; src = ""
      if (k in base) { bound = base[k]; src = "the merge-base" }
      if (k in head) {
        if (bound == "" || head[k] + 0 < bound + 0) { bound = head[k]; src = "HEAD" }
        else if (head[k] + 0 == bound + 0) { src = "the merge-base and HEAD" }
      }
      if (bound == "") next
      compared++
      if (v + 0 > bound + 0) {
        prefix = (split(line, g, "\t") >= 4 ? g[4] : k)
        printf "G\t%s\t%s\t%s\t%s\t%s\n", k, bound, v, prefix, src
      }
    }
    END { printf "C\t%d\n", compared }
  ' "$1" "$2" "$3"
}

# --- content_half: run every declared subject. Appends to content_fails, prints one line per
# subject plus a summary (point 5). Writes nothing anywhere: `stdout` mode captures to a temp file,
# `self` mode delegates to a generator flag whose whole contract is that it does not write.
content_half() {
  local line artifact gen mode args stale out hout rc col rep grew compared rkind r1 r2 r3 r4 r5 errf have_base have_head
  while IFS= read -r line; do
    # Strip a trailing CR before anything looks at the line. Under `core.autocrlf=true` this
    # here-doc arrives with one, and it used to reach the FIELDS: the leading blank line became
    # `mode=[\r]` and fell through to the unknown-mode branch, inflating content_total, while a
    # real row's last field became `--check\r` -- passed to the generator as an unknown argument,
    # which exits 2, which the old `self` branch reported as "NOT current". Three wrong answers
    # from one byte. Same class as the autocrlf case above.
    line="${line%$'\r'}"
    [ -n "$line" ] || continue
    # Exactly five `|`-separated fields, checked rather than assumed: `${line#*|}` on a row with
    # too few of them silently returns the whole remainder, so a four-field row would have put the
    # mode into `args` and read as an unknown mode instead of as a malformed declaration.
    case "$line" in
      *'|'*'|'*'|'*'|'*'|'*)
        content_total=$((content_total + 1))
        content_fails+=("declared subject line has more than five |-separated fields: $line")
        continue ;;
      *'|'*'|'*'|'*'|'*) ;;
      *)
        content_total=$((content_total + 1))
        content_fails+=("declared subject line needs five |-separated fields <artifact>|<generator>|<mode>|<mode-arg>|<stale-exit>: $line")
        continue ;;
    esac
    artifact="${line%%|*}"; line="${line#*|}"
    gen="${line%%|*}";      line="${line#*|}"
    mode="${line%%|*}";     line="${line#*|}"
    args="${line%%|*}";     stale="${line#*|}"
    [ "$args" = "-" ] && args=""
    content_total=$((content_total + 1))
    if [ ! -f "$artifact" ]; then
      content_skipped=$((content_skipped + 1))
      printf 'ok  %s: content not applicable -- no %s in this repo\n' "$NAME" "$artifact"
      continue
    fi
    if [ ! -f "$gen" ]; then
      content_fails+=("$artifact exists but its declared generator '$gen' does not -- nothing can say whether this file is current")
      continue
    fi
    case "$mode" in
      ratchet)
        col="${args#col=}"
        case "$args" in
          col=*) ;;
          *) col="" ;;
        esac
        case "$col" in
          ''|*[!0-9]*)
            content_fails+=("declared subject $artifact has mode ratchet but its fourth field is '$args', expected col=<n>")
            continue
            ;;
        esac
        content_base_rev || cannot_run "$artifact is a ratchet subject, but no merge-base with origin/HEAD or origin/main could be resolved -- fetch the default branch before running this check"
        out="$(mktemp "${TMPDIR:-/tmp}/gedc.XXXXXX")" || cannot_run "mktemp failed"
        hout="$(mktemp "${TMPDIR:-/tmp}/gedh.XXXXXX")" || cannot_run "mktemp failed"
        # "The path is not in that commit" and "git could not answer" are DIFFERENT, and reading
        # both as the first is the same defect this file's `self` branch carried: a failure
        # reported as a specific benign conclusion. `git cat-file -e` asks only the question whose
        # answer is a fact about the tree, so a broken repository reaches `cannot_run` instead of
        # being recorded as "this artifact is new, every pin in it is allowed", which is the most
        # permissive verdict this branch can produce.
        # EACH COMMITTED COPY IS OPTIONAL and an absent one leaves its temp file empty: awk runs no
        # rule for an empty file, so that side simply contributes no bound.
        have_base=0
        if git cat-file -e "$CONTENT_BASE_REV:$artifact" 2>/dev/null; then
          git show "$CONTENT_BASE_REV:$artifact" >"$out" 2>/dev/null \
            || { rm -f "$out" "$hout"; cannot_run "git could not read $artifact at the merge-base $CONTENT_BASE_REV, although the path exists there"; }
          have_base=1
        fi
        have_head=0
        if git cat-file -e "HEAD:$artifact" 2>/dev/null; then
          git show "HEAD:$artifact" >"$hout" 2>/dev/null \
            || { rm -f "$out" "$hout"; cannot_run "git could not read $artifact at HEAD, although the path exists there"; }
          have_head=1
        fi
        if [ "$have_base" -eq 0 ] && [ "$have_head" -eq 0 ]; then
          # Absent from BOTH committed copies: every key is new, and a new key is what the ratchet
          # permits. Counted as SKIPPED rather than CHECKED, so it cannot read like a comparison
          # that happened.
          rm -f "$out" "$hout"
          content_skipped=$((content_skipped + 1))
          printf 'ok  %s: content not applicable -- %s exists at neither the merge-base %s nor HEAD, so every pin in it is new\n' \
            "$NAME" "$artifact" "$CONTENT_BASE_REV"
          continue
        fi
        # The report goes through a FILE, not a `$(...)` inside the `while`'s redirect. A command
        # substitution there swallows a non-zero exit -- `set -e` does not reach inside it -- so a
        # crashed awk would read as "no records, nothing grew" and print a green line. This repo
        # has filed that exact shape (`die` inside `$( )`).
        rep="$(mktemp "${TMPDIR:-/tmp}/gedr.XXXXXX")" || cannot_run "mktemp failed"
        ratchet_report "$out" "$hout" "$artifact" "$col" >"$rep" \
          || { rm -f "$out" "$hout" "$rep"; cannot_run "the ratchet comparison of $artifact failed to run"; }
        grew=0
        compared=0
        while IFS=$'\t' read -r rkind r1 r2 r3 r4 r5; do
          case "$rkind" in
            G)
              grew=1
              content_fails+=("$artifact: a pinned value GREW -- '$r4' went from $r2 to $r3 display columns in column $col, measured against $r5. This file is a ratchet: a pin may stay as long as it is, or shrink. Re-pinning it upward is how the wall grows back, and it also turns roadmap-lead-length.sh green on the row that grew")
              ;;
            M)
              grew=1
              content_fails+=("$artifact: $r1 has a record at line $r2 with no readable column $col, so it cannot be ratcheted: $r3")
              ;;
            D)
              grew=1
              content_fails+=("$artifact: $r1 names the key '$r3' twice, at line $r2 and earlier. A baseline with a duplicate key cannot be ratcheted: the reader that CONSUMES it takes the first occurrence, so a second one is either dead weight or a disagreement nobody declared")
              ;;
            C) compared="$r1" ;;
          esac
        done <"$rep"
        rm -f "$out" "$hout" "$rep"
        # THERE IS NO "the count record was missing" GUARD HERE, and its absence is a decision.
        # One was written, and a mutant that deleted it SURVIVED the whole ratchet suite, because
        # it is unreachable by construction: awk's END block emits the count unconditionally, and
        # an awk that fails to run at all is already caught by the `|| cannot_run` above. Dead code
        # that looks like a guard is worse than no code -- the same call
        # `roadmap-lead-length.sh`'s ONLY-THE-LEAD-IS-RATCHETED comment makes about its own name-cell ratchet. What the guard was
        # reaching for is covered instead by the count being PRINTED on the green line, where a
        # comparison that looked at nothing reads as `0 pin(s) compared` and not as a clean run.
        if [ "$grew" -eq 0 ]; then
          content_checked=$((content_checked + 1))
          printf 'ok  %s: %s: no pinned value in column %s exceeds its value at the merge-base %s or at HEAD, whichever is smaller (%s pin(s) compared)\n' \
            "$NAME" "$artifact" "$col" "$CONTENT_BASE_REV" "$compared"
        fi
        ;;
      self)
        # THE DECLARED STALE CODE IS LOAD-BEARING, and calling every non-zero exit "is NOT current"
        # was wrong in a way that recommended the operation that had just been refused.
        # `backlog-toc.sh` exits 1 for "differs" but 2,3,4,5,6,7,8,9,10 for could-not-run or
        # refused -- an unknown argument, an unreadable ledger, a vocabulary it will not guess at.
        # The old branch answered "$artifact is NOT current -- regenerate it" for all of them: an
        # assertion about staleness that nothing measured, plus an instruction to run the very
        # thing that just declined. The `stdout` branch three lines away got this right ("so
        # nothing checked whether"), which is how it was found.
        case "$stale" in
          ''|*[!0-9]*)
            content_fails+=("declared subject $artifact has mode self but its fifth field is '$stale', expected the generator's exit code for 'the artifact is stale'")
            continue
            ;;
        esac
        errf="$(mktemp "${TMPDIR:-/tmp}/gede.XXXXXX")" || cannot_run "mktemp failed"
        rc=0
        # stderr is CAPTURED, not discarded. It is the only text that tells the two non-zero cases
        # apart, and sending it to /dev/null threw away exactly the evidence the could-not-run
        # message has to carry.
        # `</dev/null` IS LOAD-BEARING. stdin here is the `CONTENT_EOF` here-doc that drives the
        # subject loop, so a generator that reads stdin EATS THE REST OF THE SUBJECT LIST -- and
        # every summary number still closes, because `content_total` is itself counted by the loop.
        # Measured with a stub whose body is `cat >/dev/null`, the `self` subject moved first:
        # `content checked 1 of 1 declared subjects (0 not applicable, 0 failed)`, rc=0, with the
        # ratchet subject never examined and nothing in the output able to say so. Latent today
        # (the ratchet subject runs first) and live the moment the order changes or a second `self`
        # subject is declared. The declared-count check below is the other half of the fix: a loop
        # that counts its own iterations cannot notice that it stopped early.
        # shellcheck disable=SC2086
        /bin/bash "$gen" $args >/dev/null 2>"$errf" </dev/null || rc=$?
        if [ "$rc" -eq 0 ]; then
          content_checked=$((content_checked + 1))
          printf 'ok  %s: %s is what %s %s reports as current\n' "$NAME" "$artifact" "$gen" "$args"
        elif [ "$rc" -eq "$stale" ]; then
          content_fails+=("$artifact is NOT current: '$gen $args' exited $rc -- regenerate it: /bin/bash $gen")
        else
          content_fails+=("'$gen $args' exited $rc, which is not its declared stale code ($stale), so nothing checked whether $artifact is current. Its stderr: $(tr '\n' ' ' <"$errf" | cut -c1-300)")
        fi
        rm -f "$errf"
        ;;
      *)
        content_fails+=("declared subject $artifact has an unknown mode '$mode' (expected ratchet or self)")
        ;;
    esac
  done <<CONTENT_EOF
$CONTENT_SUBJECTS
CONTENT_EOF
  # point 5's summary, and the arithmetic has to CLOSE. The first version printed
  # `content fresh for %d of %d declared subjects (%d not applicable)` and never mentioned
  # failures, so a run with one FAIL read `0 of 2 (1 not applicable)` -- 0+1 != 2, with the missing
  # subject nowhere in the line. Worse, it printed the `ok ` prefix on a failing run, and in the
  # `not_applicable()` path it was the LAST line of an rc=1 run, so the final thing a reader saw
  # was an `ok`. Now the failed count is DERIVED (never a third counter that can disagree), the
  # four numbers always add up, and the prefix follows the verdict.
  # THE PREFIX IS `note`, NOT `ok` AND NOT `FAIL`, and the third prefix is the point rather than
  # indecision. `ok` on a failing run was the defect. `FAIL` was the first fix and it broke a
  # property the guard rests on: a FAIL line is a COUNTABLE violation, and adding a summary to that set
  # made "every violation is reported" unverifiable by counting -- measured, as ten rows using
  # `only_fail` went red at once. This line is an accounting of the violations, not one of them.
  local failed
  failed=$((content_total - content_checked - content_skipped))
  # THE EXPECTED COUNT IS A LITERAL, and that is the point: `content_total` is incremented by the
  # loop, so it can only ever agree with itself. A loop that stopped early -- because a generator
  # drained the here-doc driving it -- reports `1 of 1` and all four numbers add up. Comparing
  # against a number written OUTSIDE the loop is the only thing that can see a truncated run.
  if [ "$content_total" -ne "$CONTENT_SUBJECTS_EXPECTED" ]; then
    content_fails+=("the content half examined $content_total declared subjects but $CONTENT_SUBJECTS_EXPECTED are declared -- the subject loop did not run to the end, so the numbers below describe a truncated run")
    failed=$((failed + 1))
  fi
  printf 'note %s: content checked %d of %d declared subjects (%d not applicable, %d failed)\n' \
    "$NAME" "$content_checked" "$content_total" "$content_skipped" "$failed"
}

