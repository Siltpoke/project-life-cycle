#!/usr/bin/env bash
# gen-roadmap-lead-baseline.sh (p42) — pin what the mainline table reads like TODAY.
#
# Emits one record per mainline row:
#     <name-digest><TAB><name-cols><TAB><lead-cols><TAB><name prefix, for a human>
#
# WHY A BASELINE AND NOT A REWRITE. Measured on this repo when the rule was written: 52
# mainline rows, the name cell running to hundreds of display columns and the `what`
# cell to 3155 (median 953). A bound that reds on 50 of 52 rows on the day it lands is not a
# rule, it is a wall of red somebody switches off. Rewriting 52 rows of load-bearing prose by
# hand is hours of surgery with a real chance of losing content, and the format rules reject deleting
# detail explicitly.
#
# SO THIS IS A RATCHET, NOT AN EXEMPTION LIST. A pinned row may stay exactly as long as it is.
# It may not get LONGER. A row that is not pinned -- new, or renamed, which means somebody was
# already editing it -- must meet the bound outright.
#
# THE KEY IS THE NAME CELL, NOT THE ROW POSITION and not the backlog id. Position rots the
# first time the table is reordered. The backlog id looked promising and was measured instead
# of assumed: 51 of 52 rows carry one, ONE row carries none, and one id appears twice -- so it
# cannot identify a row on its own. A digest of the name cell can, and it has the property we
# want for free: rename a row and it stops being pinned, because renaming it is touching it.
#
# Envelope: bash + jq + awk + cksum. No python3 (CLAUDE.md).
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROADMAP="${ROADMAP_PATH:-docs/ROADMAP.md}"
LIBDIR="${EAW_LIB_DIR:-$HERE/lib}"

[ -f "$ROADMAP" ] || { printf 'gen-roadmap-lead-baseline: %s is not a regular file\n' "$ROADMAP" >&2; exit 1; }
[ -f "$LIBDIR/eaw-ranges.jq" ] || { printf 'gen-roadmap-lead-baseline: %s/eaw-ranges.jq missing\n' "$LIBDIR" >&2; exit 1; }

# shellcheck disable=SC1090
. "$HERE/lib/roadmap-lead.sh"

printf '# GENERATED by scripts/gen-roadmap-lead-baseline.sh -- do not hand-edit.\n'
printf '# One record per mainline row of %s, pinned so the table can only get SHORTER.\n' "$ROADMAP"
printf '# <name-digest>\\t<name-cols>\\t<lead-cols>\\t<name prefix>\n'
printf '#\n'
printf '# A row may stay as long as it is pinned here. It may not grow. A row that is absent --\n'
printf '# new, or renamed, which is the same thing as having been edited -- must meet the bound.\n'
printf '# Regenerate ONLY when deliberately re-pinning; the guard tells you when that is honest.\n'

roadmap_lead_rows "$ROADMAP" "$LIBDIR"
