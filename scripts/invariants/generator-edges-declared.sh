fail_lines=()

# Exemptions, one index per accepted line: script, path, table line, whether any cell of a row
# matched it (else orphan), whether a cell that failed every rule used it (else stale).
ex_script=()
ex_path=()
ex_line=()
ex_matched=()
ex_needed=()

# --- ex_find <script> <path>: sets ex_idx to the index of the exemption for that pair, or -1.
ex_find() {
  local i=0
  ex_idx=-1
  while [ "$i" -lt "${#ex_script[@]}" ]; do
    if [ "${ex_script[$i]}" = "$1" ] && [ "${ex_path[$i]}" = "$2" ]; then
      ex_idx=$i
      return 0
    fi
    i=$((i + 1))
  done
  return 1
}

# The parse below runs once into a temp file and is read twice: exemptions first, since an
# exemption line may sit anywhere in the table, then the rows. So FAIL lines come out grouped,
# not in table order: malformed and duplicate exemption lines, then rows, then orphan and stale
# exemptions. Every record field is non-empty by construction (the awk pass checks before it
# prints): `read` with IFS=TAB merges a run of TABs, so an empty field would shift the rest left.
parsed="$(mktemp "${TMPDIR:-/tmp}/gedp.XXXXXX")" || cannot_run "mktemp failed"
trap 'rm -f "$parsed"' EXIT

# --- the table parse: one awk pass, emitting one record per line worth acting on. `B` = a data
# row that does not have exactly 3 non-empty tab-separated fields (row shape violation); `R` = a
# well-formed data row. A comment (`#...`), a blank line, and the exact header line
# `generator<TAB>reads<TAB>writes` are all skipped here, before either kind is emitted -- matching
# what `scripts/select-tests.sh` and `scripts/blind_spots.py` did. NOTE: both were
# deleted with the selector, so the table now has ZERO functional readers and this parse is the
# only thing that reads it. The skip rules stay as they are -- they are the table's format, not a
# concession to a reader -- but nothing downstream depends on them any more.
# A `B` record carries the raw row with each TAB shown as `<TAB>`: the `read` below splits on TAB
# and merges runs of it, so a raw row passed through unchanged would be cut to its first field.
# A missing or untracked script does not stop its row's cells from being checked: every
# violation is reported, so such a row yields the script line AND a line per unfound cell.
awk -F'\t' '
  {
    raw = $0
    sub(/\r$/, "", raw)
    if (raw == "") next
    if (raw ~ /^#exempt/) {
      n = split(raw, f, "\t")
      shown = raw
      gsub(/\t/, "<TAB>", shown)
      if (n != 4 || f[1] != "#exempt" || f[2] == "" || f[3] == "")
        printf "M\t%d\tneeds #exempt<TAB>script<TAB>path<TAB>reason, exactly 4 tab-separated fields\t%s\n", NR, shown
      else if (f[4] ~ /^[[:space:]]*$/)
        printf "M\t%d\tthe reason is empty\t%s\n", NR, shown
      else
        printf "X\t%d\t%s\t%s\n", NR, f[2], f[3]
      next
    }
    if (raw ~ /^#/) next
    if (raw == "generator\treads\twrites") next
    n = split(raw, f, "\t")
    if (n != 3 || f[1] == "" || f[2] == "" || f[3] == "") {
      shown = raw
      gsub(/\t/, "<TAB>", shown)
      printf "B\t%d\t%s\n", NR, shown
    } else {
      printf "R\t%d\t%s\t%s\t%s\n", NR, f[1], f[2], f[3]
    }
  }
' "$TABLE" >"$parsed"

while IFS=$'\t' read -r kind ln f1 f2; do
  case "$kind" in
    M) fail_lines+=("$TABLE:$ln: malformed exemption line ($f1): $f2") ;;
    X)
      if ex_find "$f1" "$f2"; then
        fail_lines+=("$TABLE:$ln: duplicate exemption for '$f1' '$f2' (first at line ${ex_line[$ex_idx]})")
      else
        ex_script+=("$f1"); ex_path+=("$f2"); ex_line+=("$ln"); ex_matched+=(0); ex_needed+=(0)
      fi
      ;;
  esac
done <"$parsed"

while IFS=$'\t' read -r kind ln f1 f2 f3; do
  case "$kind" in B|R) ;; *) continue ;; esac
  rows=$((rows + 1))
  if [ "$kind" = "B" ]; then
    fail_lines+=("$TABLE:$ln: a data row needs exactly 3 non-empty tab-separated fields: $f1")
    continue
  fi
  generator="$f1"; reads_cell="$f2"; writes_cell="$f3"

  state="$(script_state "$generator")"
  case "$state" in
    missing) fail_lines+=("$TABLE:$ln: script '$generator' is missing or not a regular file") ;;
    untracked) fail_lines+=("$TABLE:$ln: script '$generator' is not tracked by git") ;;
  esac

  for role in reads writes; do
    if [ "$role" = "reads" ]; then cell="$reads_cell"; else cell="$writes_cell"; fi
    [ "$cell" = "-" ] && continue
    path_cells=$((path_cells + 1))
    passed=0
    if point1_found "$cell" "$generator"; then
      passed=1
    elif [ "$role" = "writes" ] && header_ok "$cell" "$generator"; then
      by_header=$((by_header + 1))
      passed=1
    fi
    if ex_find "$generator" "$cell"; then
      ex_matched[$ex_idx]=1
      if [ "$passed" -eq 0 ]; then
        ex_needed[$ex_idx]=1
        continue
      fi
    fi
    [ "$passed" -eq 1 ] && continue
    if [ "$role" = "writes" ]; then
      fail_lines+=("$TABLE:$ln: writes cell '$cell' is not named in '$generator' outside comments, and no tracked '$cell' carries a first-line 'GENERATED by $generator' header")
    else
      fail_lines+=("$TABLE:$ln: reads cell '$cell' is not named in '$generator' outside comments")
    fi
  done
done <"$parsed"

i=0
while [ "$i" -lt "${#ex_script[@]}" ]; do
  pair="'${ex_script[$i]}' '${ex_path[$i]}'"
  if [ "${ex_matched[$i]}" -eq 0 ]; then
    fail_lines+=("$TABLE:${ex_line[$i]}: exemption for $pair matches no row naming that script with that path")
  elif [ "${ex_needed[$i]}" -eq 0 ]; then
    fail_lines+=("$TABLE:${ex_line[$i]}: exemption for $pair is stale: every cell it names passes without it, by point 1 or the header rule")
  else
    exemptions=$((exemptions + 1))
  fi
  i=$((i + 1))
done

