"""the display-width table in `scripts/lib/eaw-ranges.jq` is correct, and
this bench can tell when it is not.

WHAT REPLACED WHAT. Spec rev 2 carried a hand-written threshold
(`if . > 0x2E80 then 2 else 1 end`) that (a) could not parse -- jq has no hex
literal -- and (b) was described as "conservative, never under-counts" while
returning 1 for U+1100 and U+2329, both East_Asian_Width=W. The replacement is a
table EXPORTED from the Unicode database by `scripts/gen-eaw-ranges.py` and
frozen as a jq literal, so the gate stays jq-only while nobody hand-picks which
codepoints are wide.

WHY BOUNDARIES AND NOT SAMPLING. An off-by-one at a range edge is the defect this
kind of table actually gets, and uniform sampling over 1.1M codepoints is very
unlikely to land on one. `test_every_range_boundary` checks `start-1`, `start`,
`end`, `end+1` for every range -- the four points where an off-by-one shows.

WHY THE MUTANT IS NOT OPTIONAL. `test_every_range_boundary` passing and "the
bench compared nothing" produce identical output. `test_mutant_off_by_one_is_
caught` shifts one range start by a single codepoint and requires exactly the
disagreement that shift implies. Without it the boundary test is not evidence.

WHERE THE EXPECTATIONS COME FROM, and why that changed (p35). They used to be
re-derived from `unicodedata` at run time, on the reasoning that a live oracle
keeps the table and its expectations moving together. That reasoning has one
unstated premise -- that the interpreter running the test ships the same Unicode
version the table was exported from -- and CI did not satisfy it. CI ran Python
3.12 (unidata 15.0.0) against a table declaring 15.1.0, so the three comparison
tests below SKIPPED on every CI run since the table landed, and every local
interpreter here is 3.13, so nothing anywhere was checking the table.

MEASURED, both arms, with `[4352,4447]` mutated to `[4352,4448]`:
    Python 3.10 (unidata 13.0.0)  ->  11 passed, 3 skipped, exit 0   <- a wrong table, green
    Python 3.13 (unidata 15.1.0)  ->  3 failed                       <- the control

So the expectations are now a pinned export, `scripts/lib/eaw-boundary-widths.json`,
written by the same generator from the same database read as the table. The
comparison tests read it instead of the live database and therefore have an oracle
on every interpreter. The original worry was right about one thing and it is
handled: a frozen expectation file COULD drift from the table -- so both files are
regenerated by one generator, and the version-gated sync test below checks both.

WHAT IS LEFT VERSION-GATED, deliberately and exactly one test. Table and snapshot
share a source, so they can prove they agree with each other and cannot prove the
generator read the database correctly. That claim needs the live database and has
no oracle under version skew. It lives in `test_table_and_snapshot_are_what_the_
generator_produces_today`, and p35's other half makes that skip loud in CI rather
than silent.
"""
import json
import shutil
import re
import subprocess
import sys
import unicodedata
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
TABLE = REPO / "scripts" / "lib" / "eaw-ranges.jq"
SNAPSHOT = REPO / "scripts" / "lib" / "eaw-boundary-widths.json"
GENERATOR = REPO / "scripts" / "gen-eaw-ranges.py"

def _snapshot():
    """The pinned expectations. Read once, asserted non-vacuous at the point of use.

    A missing or empty snapshot must be a FAILURE and never an empty comparison: a
    boundary test over zero points passes and prints the same thing a real one does.
    """
    doc = json.loads(SNAPSHOT.read_text())
    widths = {int(k): v for k, v in doc.get("widths", {}).items()}
    return doc, widths


def _table_ranges():
    """The ranges the COMMITTED table declares, parsed out of the .jq text.

    Interpreter-independent by construction: it reads two committed files and never
    touches `unicodedata`. That matters because it is what lets the coverage assertion
    below run on the same machines the comparisons now run on -- an assertion that only
    holds on a version-matching interpreter would leave the coverage claim exactly as
    unguarded as the comparisons used to be.

    Replaces a `_live_ranges()` that walked the running database. That helper had ZERO
    callers by the time this phase shipped -- the version-gated test shells out to the
    generator instead -- and its docstring told the reader there was a live-database path
    in this file when there was none.
    """
    body = TABLE.read_text()
    start = body.index("def wide_ranges:")
    end = body.index("];", start)
    pairs = re.findall(r"\[\s*(\d+)\s*,\s*(\d+)\s*\]", body[start:end])
    assert pairs, "no ranges parsed out of %s -- the table's shape changed" % TABLE
    return [(int(a), int(b)) for a, b in pairs]


def _jq_widths(codepoints, table_dir, module="eaw-ranges"):
    """Run the frozen table over a list of codepoints, in jq, and return widths."""
    proc = subprocess.run(
        ["jq", "-R", "-n",
         'include "%s" {search:"%s"}; [inputs|tonumber|cw]' % (module, table_dir)],
        input="\n".join(str(c) for c in codepoints),
        capture_output=True, text=True,
    )
    assert proc.returncode == 0, "jq failed: %s" % proc.stderr
    return json.loads(proc.stdout)


pytestmark = pytest.mark.skipif(shutil.which("jq") is None, reason="jq not installed")


@pytest.fixture(scope="module")
def expected_widths():
    """The pinned oracle: {codepoint: expected width} at every range boundary.

    The floor is the same one the generator refuses to emit below. It is asserted on
    BOTH sides on purpose -- a generator check alone would pass a snapshot that was
    later truncated by hand, and this fixture feeds every comparison below.
    """
    _, widths = _snapshot()
    assert len(widths) > 100, (
        "the snapshot carries only %d boundary points — too few to mean anything; "
        "regenerate it with `python3 scripts/gen-eaw-ranges.py --snapshot`" % len(widths)
    )
    assert set(widths.values()) == {1, 2}, (
        "the snapshot's widths are %s; a snapshot that recorded one value everywhere "
        "would make every comparison below pass while distinguishing nothing"
        % sorted(set(widths.values()))
    )
    return widths


@pytest.fixture(scope="module")
def boundary_points(expected_widths):
    return sorted(expected_widths)


def test_the_snapshot_covers_exactly_the_table_s_boundary_points(expected_widths):
    """The coverage SET, not just its size -- and interpreter-independent.

    MEASURED, and this is why it exists. `boundary_points` used to be built inside this
    file from a live `unicodedata` walk; it is now `sorted(expected_widths)`, i.e. whatever
    the generator chose to write. The only things left guarding that were `len > 100` and
    `set(values) == {1, 2}`, and both survive a generator that stopped probing `end + 1`:
    the point count drops 429 -> 329, both floors pass, and THE PHASE'S OWN CANONICAL
    MUTANT -- `[4352,4447]` -> `[4352,4448]` -- then survives with `14 passed`. On a skewed
    interpreter that reads `14 passed, 1 skipped, exit 0`: a wrong table and a green run,
    which is the sentence this phase exists to make impossible.

    So assert the correspondence directly: every range in the COMMITTED table contributes
    exactly `start-1, start, end, end+1` (clipped to the codepoint space) and the snapshot
    holds exactly that set. Both sides are read from committed files, so this runs wherever
    the comparisons run -- a version-gated version of this check would leave the coverage
    claim as unguarded as the comparisons used to be.

    It does NOT prove the generator read the database correctly; the table and the snapshot
    still share a source. That is filed separately and is deliberately out of scope here.
    """
    want = set()
    for a, b in _table_ranges():
        for p in (a - 1, a, b, b + 1):
            if 0 <= p < 0x110000:
                want.add(p)
    got = set(expected_widths)
    missing, extra = sorted(want - got), sorted(got - want)
    assert not missing and not extra, (
        "the snapshot's key set is not the table's boundary points: %d missing "
        "(first few %s), %d extra (first few %s). Regenerate BOTH pinned files from one "
        "interpreter." % (len(missing), missing[:5], len(extra), extra[:5])
    )


# --------------------------------------------------------------------------- version gate
# THE TABLE IS A PINNED EXPORT, NOT A VIEW OF THE RUNNING PYTHON. Its header records the
# Unicode version it was generated from; `unicodedata` reports whatever the interpreter
# happens to ship. Those two are equal on the machine that generated it and on no other
# guarantee at all.
#
# HISTORY, past tense, and it is why the gate exists at all. On one CI run the
# table declared 15.1.0 (Python 3.13) while CI ran Python 3.12 (unicodedata 15.0.0); three
# codepoints moved between those releases -- U+2FFC, U+2FFF, U+31EF -- and four tests went
# red against a table that was correct. Nothing local could have found it: every local
# interpreter here is 3.13.
#
# AS OF p35 THIS BLOCK GOVERNS ONE TEST, NOT THREE, and CI runs 3.13. The comparisons read
# the pinned snapshot and are gate-free by construction; the only thing still gated is
# `test_table_and_snapshot_are_what_the_generator_produces_today`, whose claim genuinely
# needs the live database. The gate is LOUD, and p35's CI step turns its skip into a red --
# a silent skip is how this table went unchecked for weeks.


def _declared_unicode_version() -> str:
    """The version the table says it came from, read from its own header."""
    m = re.search(r"unicodedata ([0-9]+\.[0-9]+\.[0-9]+)", TABLE.read_text()[:600])
    return m.group(1) if m else ""


UNICODE_SKEW = _declared_unicode_version() != unicodedata.unidata_version
SKEW_REASON = (
    "Unicode version skew: the table declares %s, this interpreter reports %s. The table is a "
    "PINNED export and is not wrong; this comparison simply has no oracle here. Run it on a "
    "Python whose unicodedata matches, or regenerate BOTH pinned files there -- "
    "`python3 scripts/gen-eaw-ranges.py > scripts/lib/eaw-ranges.jq` AND "
    "`python3 scripts/gen-eaw-ranges.py --snapshot > scripts/lib/eaw-boundary-widths.json`. "
    "Regenerating one of the pair leaves the other an oracle for a table that no longer "
    "exists, and costs a second red cycle to find out." % (
        _declared_unicode_version() or "(none recorded)", unicodedata.unidata_version)
)
needs_matching_unicode = pytest.mark.skipif(UNICODE_SKEW, reason=SKEW_REASON)


def test_the_version_gate_is_not_hiding_a_missing_declaration():
    """The gate above must never be satisfied by a table that records no version at all --
    that would turn "we cannot compare" into "there is nothing to compare against".

    This asserts that the table RECORDS a version, never that the version matches this
    interpreter. An older form asserted `unicodedata.unidata_version in head`, which quietly
    required the running Python to be the one the table was generated on -- not a property
    of the table, a property of the machine, and it made a correct table fail on CI. A second
    test used to restate this same predicate (`re.search` over the same 600-byte slice, which
    is exactly what `_declared_unicode_version` does); it was removed rather than kept,
    because one mutation killed both and the second contributed a failure line, not coverage.
    """
    assert _declared_unicode_version(), (
        "the table records no Unicode version in its header, so the skip condition above "
        "cannot mean what it says"
    )


@needs_matching_unicode
def test_table_and_snapshot_are_what_the_generator_produces_today():
    """THE ONE REMAINING VERSION-GATED TEST, and the only claim that needs the live
    database: both pinned files are reproducible from `unicodedata` as it is here.

    Everything else in this file compares the table against the snapshot, which proves
    the two agree and says nothing about whether their shared source was read correctly.
    This is that missing half. It has no oracle when the interpreter's Unicode version
    differs from the table's header -- that is not a defect to route around, it is the
    honest scope of the claim -- so under skew it skips, and p35's CI guard turns that
    skip red instead of letting it pass unnoticed.

    Both files are checked in one test because one generator emits both: a version of
    this that covered only the table would let the snapshot rot while reporting green.
    """
    # sys.executable, NOT PATH `python3`. MEASURED: with the test interpreter on 3.13 (so
    # UNICODE_SKEW is False and this gate is OPEN) and PATH `python3` shimmed to 3.10, the
    # generator emitted a 13.0.0 header and this byte-compare FAILED against a correct,
    # unmodified table. The gate above reads THIS process's `unicodedata`, so the subprocess
    # has to be this process, or the gate is guarding a different interpreter than the one
    # it measured -- the same false red the note at the end of this test says was removed.
    proc = subprocess.run(
        [sys.executable, str(GENERATOR)], capture_output=True, text=True, cwd=REPO,
    )
    if proc.returncode != 0:
        pytest.skip("generator did not run under %s: %s" % (
            sys.executable, proc.stderr.strip()[:120]))
    assert proc.stdout == TABLE.read_text(), (
        "scripts/lib/eaw-ranges.jq is not what gen-eaw-ranges.py produces — "
        "regenerate it rather than hand-editing"
    )

    snap = subprocess.run(
        [sys.executable, str(GENERATOR), "--snapshot"], capture_output=True, text=True, cwd=REPO,
    )
    assert snap.returncode == 0, "generator --snapshot failed: %s" % snap.stderr.strip()[:200]
    assert snap.stdout == SNAPSHOT.read_text(), (
        "scripts/lib/eaw-boundary-widths.json is not what "
        "`gen-eaw-ranges.py --snapshot` produces — regenerate it rather than hand-editing"
    )


def test_snapshot_and_table_came_from_the_same_unicode_version():
    """Both files are pinned exports; if their recorded versions differ they were
    produced by two different runs, and the snapshot is then an oracle for a table that
    no longer exists.

    Interpreter-independent BY CONSTRUCTION -- it compares two committed files and never
    reads `unicodedata` -- which is what makes it the check that still works on the day
    the version-gated test above goes quiet.
    """
    doc, _ = _snapshot()
    assert doc.get("unicode_version") == _declared_unicode_version(), (
        "the table declares Unicode %s and the snapshot declares %s; regenerate both from "
        "one interpreter" % (_declared_unicode_version() or "(none)", doc.get("unicode_version"))
    )


def test_every_range_boundary(boundary_points, expected_widths):
    """The four points per range where an off-by-one shows. Read with the mutant test.

    No version gate any more (p35): the oracle is the pinned snapshot, so this runs on
    every interpreter — including the one CI happens to install.
    """
    got = _jq_widths(boundary_points, str(TABLE.parent))
    want = [expected_widths[cp] for cp in boundary_points]
    assert len(got) == len(want)
    bad = [(cp, w, g) for cp, w, g in zip(boundary_points, want, got) if w != g]
    assert bad == [], "width disagreements at %d boundary points, first few: %s" % (
        len(bad), bad[:5])


def test_mutant_off_by_one_is_caught(tmp_path, boundary_points, expected_widths):
    """Negative control aimed at the bench.

    Shift one range's start up by a single codepoint. Exactly one boundary point
    must change answer — the old start, which is wide and would now read narrow.
    Asserting the COUNT, not merely "something changed", keeps this from passing
    for the wrong reason (e.g. a mangled table that breaks every lookup).
    """
    text = TABLE.read_text()
    lines = text.split("\n")
    idx = next(i for i, l in enumerate(lines) if l.strip().startswith("[19968,"))
    a, rest = lines[idx].strip().lstrip("[").split(",", 1)
    lines[idx] = "  [%d,%s" % (int(a) + 1, rest)
    mutant = tmp_path / "eaw-ranges.jq"
    mutant.write_text("\n".join(lines))
    assert mutant.read_text() != text, "mutation did not apply — this control proves nothing"

    got = _jq_widths(boundary_points, str(tmp_path))
    want = [expected_widths[cp] for cp in boundary_points]
    bad = [cp for cp, w, g in zip(boundary_points, want, got) if w != g]
    assert bad == [19968], (
        "the off-by-one mutant should flip exactly U+4E00 (19968) and nothing else; got %s" % bad)


@pytest.mark.parametrize("ch, want, why", [
    ("a", 1, "ASCII, Na"),
    ("\u4e2d", 2, "U+4E2D, CJK Wide. Written as an escape, not as the character: this\n                    file is shipped bytes and the CJK rule refuses CJK outside docs/.\n                    The escape is the same codepoint, so the case is unchanged"),
    ("ᄀ", 2, "U+1100 — rev 2's threshold returned 1 for this; an already-verified red"),
    ("〈", 2, "U+2329 — the second character rev 2's 'never under-counts' claim missed"),
    ("✅", 2, "U+2705, W — the threshold got this wrong too, and it is used in this repo's ROADMAP"),
    ("▶", 1, "U+25B6 is Ambiguous; counting it 1 is the DECLARED choice, not an accident"),
    ("⚠", 1, "U+26A0 is Ambiguous — same declared choice"),
])
def test_named_characters(ch, want, why):
    got = _jq_widths([ord(ch)], str(TABLE.parent))[0]
    assert got == want, "%s (%s): got %d, want %d" % (ch, why, got, want)


def test_dispwidth_over_a_step_line():
    """The unit the 60-column bound is measured in: a rendered step line with its
    `sN ` prefix, per the station-plan format."""
    proc = subprocess.run(
        ["jq", "-rn",
         'include "eaw-ranges" {search:"%s"}; ("s1 \\u91cf\\u51fa\\u5224\\u636e"|dispwidth)' % TABLE.parent],
        capture_output=True, text=True,
    )
    assert proc.returncode == 0, proc.stderr
    # "s1 " is 3 single-width; the four CJK characters (U+91CF U+51FA U+5224 U+636E, all
    # East-Asian Wide) are 2 columns each -> 3 + 8 = 11. Written as \u escapes above
    # rather than as the characters: this file is shipped bytes and the CJK rule refuses
    # CJK outside docs/. jq decodes them to the same string, so the input is unchanged.
    assert proc.stdout.strip() == "11"


def test_empty_string_is_zero():
    """`add` over an empty array is null in jq; the table's `// 0` covers it. A
    null here would make an empty step read as unmeasurable rather than as zero."""
    proc = subprocess.run(
        ["jq", "-rn", 'include "eaw-ranges" {search:"%s"}; (""|dispwidth)' % TABLE.parent],
        capture_output=True, text=True,
    )
    assert proc.returncode == 0, proc.stderr
    assert proc.stdout.strip() == "0"
