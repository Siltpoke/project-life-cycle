# --- tracked <path>: is <path> itself, byte-literal, in git's index?
tracked() {
  git --literal-pathspecs ls-files --error-unmatch -- "$1" >/dev/null 2>&1
}

# --- point1_found <path> <script>: point 1's match, as an awk pass over <script>. Truncates each line at
# the first `#` at line start or preceded by space/tab, then scans the survivor with index() in
# a loop -- so a boundary miss on one occurrence does not stop the search -- for a fixed-string
# occurrence of <path> obeying the asymmetric boundary above.
point1_found() {
  local path="$1" script="$2"
  [ -r "$script" ] || return 1
  GEDP_PATH="$path" awk '
    BEGIN { path = ENVIRON["GEDP_PATH"]; plen = length(path) }
    !found {
      line = $0
      n = length(line)
      cut = 0
      for (i = 1; i <= n; i++) {
        if (substr(line, i, 1) == "#") {
          if (i == 1) { cut = i; break }
          prevc = substr(line, i - 1, 1)
          if (prevc == " " || prevc == "\t") { cut = i; break }
        }
      }
      if (cut > 0) line = substr(line, 1, cut - 1)
      ln = length(line)
      start = 1
      while (1) {
        p = index(substr(line, start), path)
        if (p == 0) break
        pos = start + p - 1
        before_ok = 1
        if (pos > 1) {
          bc = substr(line, pos - 1, 1)
          if (bc ~ /[A-Za-z0-9._]/) before_ok = 0
        }
        after_ok = 1
        endpos = pos + plen
        if (endpos <= ln) {
          ac = substr(line, endpos, 1)
          if (ac ~ /[A-Za-z0-9._\/-]/) after_ok = 0
        }
        if (before_ok && after_ok) { found = 1; break }
        start = pos + 1
      }
    }
    END { exit (found ? 0 : 1) }
  ' "$script"
}

# --- header_ok <target> <script>: point 2 rule 2. <target> must be a git-tracked regular file whose
# FIRST LINE contains the literal text "GENERATED by <script>" followed by a space or end of
# line. <script> is matched exactly -- "GENERATED by scripts/g.sh" does not vouch for a header
# reading "GENERATED by scripts/g.shx" or naming a different script.
header_ok() {
  local target="$1" script="$2"
  [ -f "$target" ] || return 1
  tracked "$target" || return 1
  local first=""
  IFS= read -r first <"$target" || true
  first="${first%$'\r'}"
  case "$first" in
    *"GENERATED by $script "*) return 0 ;;
    *"GENERATED by $script") return 0 ;;
    *) return 1 ;;
  esac
}

# --- script_state <script>: is the script cell itself a git-tracked regular file? Prints one of
# ok / missing / untracked to stdout (never a violation reason by itself -- the caller composes
# the message so it can name the row).
script_state() {
  local s="$1"
  [ -f "$s" ] || { printf 'missing\n'; return; }
  tracked "$s" || { printf 'untracked\n'; return; }
  printf 'ok\n'
}

